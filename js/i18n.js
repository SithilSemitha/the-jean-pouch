  var DICT = { en: EN, si: SI, ta: TA };
  var listeners = [];
  var lang = "en";

  function initialLang() {
    var saved = null;
    try { saved = localStorage.getItem(STORE_KEY); } catch (e) { /* storage unavailable */ }
    if (LANGS.indexOf(saved) !== -1) return saved;
    var device = (navigator.language || "en").slice(0, 2).toLowerCase();
    return LANGS.indexOf(device) !== -1 ? device : "en";
  }

  /** Translate a key. {name}-style placeholders are filled from vars. */
  function t(key, vars) {
    var text = DICT[lang][key];
    if (text === undefined) text = EN[key];
    if (text === undefined) return key;
    return text.replace(/\{(\w+)\}/g, function (m, k) { return vars && vars[k] !== undefined ? vars[k] : m; });
  }

  /** For content that is either a plain string or { en, si, ta }. */
  function pick(value) {
    if (value === null || typeof value !== "object") return value;
    return value[lang] !== undefined ? value[lang] : value.en;
  }

  function applyToPage() {
    document.documentElement.lang = lang;
    Array.prototype.forEach.call(document.querySelectorAll("[data-i18n]"), function (node) {
      node.textContent = t(node.getAttribute("data-i18n"));
    });
    Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-label]"), function (node) {
      node.setAttribute("aria-label", t(node.getAttribute("data-i18n-label")));
    });
  }

  function set(next) {
    if (LANGS.indexOf(next) === -1) return;
    lang = next;
    try { localStorage.setItem(STORE_KEY, lang); } catch (e) { /* storage unavailable */ }
    applyToPage();
    listeners.forEach(function (fn) { fn(lang); });
  }

  function init() {
    // The page's own text is the English source for every data-i18n key.
    Array.prototype.forEach.call(document.querySelectorAll("[data-i18n]"), function (node) {
      var key = node.getAttribute("data-i18n");
      if (EN[key] === undefined) EN[key] = node.textContent;
    });
    Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-label]"), function (node) {
      var key = node.getAttribute("data-i18n-label");
      if (EN[key] === undefined) EN[key] = node.getAttribute("aria-label");
    });
    lang = initialLang();
    applyToPage();
  }

  return {
    init: init, t: t, pick: pick, set: set,
    current: function () { return lang; },
    onChange: function (fn) { listeners.push(fn); }
  };
